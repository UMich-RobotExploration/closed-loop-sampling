"""Observation-guided diffusion (DPS): the analysis update of the closed loop.

Implements Sec. III-C / Alg. 1 lines 14-22: each ensemble member is
regenerated by a guided EDM pass. At every Heun step, the gradient of the
observation misfit
    L = R^{-1} || H_p(P_tar phi_D(x0_hat)) - y ||^2
is backpropagated through BOTH the frozen denoiser and the frozen autoencoder
decoder with respect to the current noisy latent, and subtracted with a fixed
guidance scale lambda_g (constant schedule; the per-(region, variable, fleet)
values live in configs/experiments/guidance_scales.yaml). The misfit observes
the TARGET VARIABLE ONLY. The guided frame is predicted frame 0 (+6 h) — the
loop convention.

Port note: this is one implementation distilled from the production pair
(the legacy temperature path and the single-variable call of the multivariate
module, which share the identical guided Heun loop). The legacy temperature
path additionally carried a vestigial second misfit term (salinity toward
zero at sigma = 1e3, approximately 4e-8 relative weight) kept there for exact
regression against earlier runs; it is numerically inert and is not ported.

The unconditional dynamics mirror forecast.edm.edm_sample exactly (same
edm_denoise, same Heun steps), so guidance scale 0 reproduces the prior member
up to bf16 nondeterminism. Denoiser forward: bf16 autocast on CUDA;
measurement decode: fp32, differentiable.
"""
from __future__ import annotations

from typing import Optional

import torch

from closedloop_sampling.forecast.edm import edm_denoise, sigmas_karras

# EDM constants as trained/run.
SIGMA_MIN = 0.002
SIGMA_MAX = 80.0
SIGMA_DATA = 0.5
N_SAMPLING_STEPS = 20

# The loop assimilates the first (+6 h) predicted frame.
OBS_FRAME_LOOP = 0

# CRN constants of the guided re-generation start noise (production values):
# seed = member_seed + cycle*CYCLE_SEED_STRIDE + GUIDED_SEED_OFFSET
#        + rseed*GUIDED_RSEED_STRIDE
GUIDED_SEED_OFFSET = 222333
GUIDED_RSEED_STRIDE = 7


def guided_start_noise(seed: int, pred_shape, device,
                       sigma_max: float = SIGMA_MAX) -> torch.Tensor:
    """Common-random-numbers start noise for one member's guided pass:
    x_start = randn(pred_shape) * sigma_max from a generator seeded `seed`."""
    g = torch.Generator(device=device)
    g.manual_seed(seed)
    return torch.randn(pred_shape, generator=g, device=device) * sigma_max


def obs_misfit(frame_norm: torch.Tensor, dcae, latent_norm, pixel_norm,
               rows, cols, y, sigma: float, channel: int) -> torch.Tensor:
    """L = || field[obs] - y ||^2 / sigma^2 for the target channel.
    Differentiable: fp32 decode, no autocast. Scalar tensor."""
    x = latent_norm.denormalize_dynamic_tensor(frame_norm.float())
    pix = pixel_norm.denormalize_dynamic_tensor(dcae.decode(x))
    field = pix[0, channel]
    r = torch.as_tensor(rows, device=field.device, dtype=torch.long)
    c = torch.as_tensor(cols, device=field.device, dtype=torch.long)
    yv = torch.as_tensor(y, device=field.device, dtype=field.dtype)
    return ((field[r, c] - yv) ** 2).sum() / (sigma ** 2)


def guided_update(
    model, dcae, latent_norm, pixel_norm,
    conditioning: torch.Tensor,      # (1, C, 1, H, W) normalized analysis latent
    x_start: torch.Tensor,           # (1, C, T_pred, H, W) = randn * sigma_max (CRN)
    rows, cols, y, sigma: float, channel: int,
    guidance_scale: float,
    obs_frame: int = OBS_FRAME_LOOP,
    sigma_min: float = SIGMA_MIN,
    sigma_max: float = SIGMA_MAX,
    sigma_data: float = SIGMA_DATA,
    n_steps: int = N_SAMPLING_STEPS,
    device: Optional[torch.device] = None,
) -> torch.Tensor:
    """One member's guided re-generation. Returns the clean latent block
    (1, C, T_pred, H, W); the loop retains frame 0.

    Fixed guidance: x <- HeunStep(x) - lambda_g * grad_x L, lambda_g constant
    across the 20 steps (the production schedule).
    """
    if device is None:
        device = next(model.parameters()).device
    sigmas = sigmas_karras(n_steps, sigma_min, sigma_max, device=device)
    x = x_start.clone()
    ac = torch.autocast(device_type=device.type, dtype=torch.bfloat16,
                        enabled=(device.type == "cuda"))
    for i in range(n_steps):
        sigma_hat = sigmas[i]
        sigma_next = sigmas[i + 1]
        x = x.detach().requires_grad_(True)
        with ac:
            x0 = edm_denoise(model, x, sigma_hat, conditioning, sigma_data)
        frame = x0[:, :, obs_frame]
        L = obs_misfit(frame, dcae, latent_norm, pixel_norm,
                       rows, cols, y, sigma, channel)
        g = torch.autograd.grad(L, x)[0].detach()
        x_d = x.detach()
        x0_d = x0.detach()
        with torch.no_grad():
            d = (x_d - x0_d) / sigma_hat
            x_next = x_d + d * (sigma_next - sigma_hat)
            if sigma_next.item() > 0:
                with ac:
                    x0n = edm_denoise(model, x_next, sigma_next, conditioning,
                                      sigma_data)
                d_next = (x_next - x0n) / sigma_next
                x_uncond = x_d + (d + d_next) * 0.5 * (sigma_next - sigma_hat)
            else:
                x_uncond = x_next
            x = (x_uncond - guidance_scale * g).detach()
    return x
